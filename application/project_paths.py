"""Where the application scripts read their inputs and write their outputs.

Every script in this folder takes its default locations from this module
(b_infty_offline.py has none and is always given --result-dir), so a new
machine needs at most this one file edited. Each location can instead be set
by an environment variable, which leaves the code untouched.

Default layout, relative to the repository root
-----------------------------------------------
    data/
        df_chexpert_plus_240401.csv        CheXpert-Plus table (report
                                           sections, demographics)
        CheXpert-v1.0-small/               downsampled CheXpert release
            train.csv                      canonical labels
            train/patient*/study*/*.jpg    images
        prepared_historycombined_canonical_blank0_source1200_bow/
                                           written by the preparation script,
                                           read by every later script
    results/
        pneumothorax_history_bow_nT200_valid200_strifle_shapley/
            raw_results.csv, ...           main run
            epsilon_replay/                replay_gate_epsilon.py
            suptrans_recompute/            recompute_suptrans_three_step.py
            block_strength/                block_strength_diagnostic.py
            tables/                        make_endpoint_tables.py
            b_infty.csv                    b_infty_offline.py
        pneumothorax_history_bow_nT200_valid200_strifle_shapley__negctrl_permuted_source/
                                           run_negative_control_shuffled_source.py
        (the n_T = 400 arm writes the same two folders with nT400 in the name;
        the simulation writes its batches to results/<batch>, see simulation/)

Neither folder belongs in the repository: CheXpert may not be redistributed,
and everything under results/ is regenerated by the scripts.

Environment variables
---------------------
    STRIFLE_DATA_DIR            default <repo>/data
    STRIFLE_CHEXPERT_PLUS_CSV   default $STRIFLE_DATA_DIR/df_chexpert_plus_240401.csv
    STRIFLE_CHEXPERT_DIR        default $STRIFLE_DATA_DIR/CheXpert-v1.0-small
    STRIFLE_PREP_DIR            default $STRIFLE_DATA_DIR/prepared_historycombined_canonical_blank0_source1200_bow
    STRIFLE_RESULTS_DIR         default <repo>/results

Pretrained weights are downloaded and cached by torchvision (under TORCH_HOME)
and by hi-ml-multimodal, outside these folders.
"""

import os

APP_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(APP_DIR)


def _location(variable, default):
    """The environment variable when it is set and nonempty, else the default."""
    value = os.environ.get(variable, "").strip()
    return os.path.abspath(os.path.expanduser(value)) if value else default


DATA_DIR = _location("STRIFLE_DATA_DIR", os.path.join(REPO_ROOT, "data"))
CHEXPERT_PLUS_CSV = _location(
    "STRIFLE_CHEXPERT_PLUS_CSV",
    os.path.join(DATA_DIR, "df_chexpert_plus_240401.csv"),
)
CHEXPERT_DIR = _location(
    "STRIFLE_CHEXPERT_DIR", os.path.join(DATA_DIR, "CheXpert-v1.0-small")
)
PREP_DIR = _location(
    "STRIFLE_PREP_DIR",
    os.path.join(DATA_DIR, "prepared_historycombined_canonical_blank0_source1200_bow"),
)
RESULTS_DIR = _location("STRIFLE_RESULTS_DIR", os.path.join(REPO_ROOT, "results"))

# Appended to a main run's directory to name its negative control.
NEGCTRL_SUFFIX = "__negctrl_permuted_source"


def run_dir(n_t, n_valid=200):
    """Result directory of one arm of the main pipeline.

    Named after n_T and the validation size, so the n_T = 200 and n_T = 400
    arms never share a directory and the pipeline's resume logic cannot pick
    up the other arm's finished repeats.
    """
    return os.path.join(
        RESULTS_DIR,
        f"pneumothorax_history_bow_nT{int(n_t)}_valid{int(n_valid)}_strifle_shapley",
    )
